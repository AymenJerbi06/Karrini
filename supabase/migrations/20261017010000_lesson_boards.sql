-- Live lesson boards, private page assets, and group-scoped published materials.
-- Existing materials remain whole-class documents (group_id is null).
-- CASE keeps unrelated storage paths / realtime topics from raising invalid UUID casts.
create function public.board_uuid(value text)
returns uuid language sql immutable set search_path = public as $$
  select case when value ~ '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$' then value::uuid else null end;
$$;
create table public.lesson_boards (
  session_id uuid primary key references public.sessions(id) on delete cascade,
  class_id text not null references public.classes(id) on delete cascade,
  -- Keep the original group id even if a timetable group is later removed.
  -- Deleting a group must never turn a private board into a whole-class board.
  group_id uuid,
  teacher_id uuid not null references public.profiles(id) on delete cascade,
  document jsonb not null,
  revision bigint not null check (revision >= 0),
  updated_at timestamptz not null default now(),
  check (jsonb_typeof(document) = 'object' and document->>'version' = '1'),
  check (jsonb_typeof(document->'pages') = 'array' and jsonb_array_length(document->'pages') between 1 and 80),
  check (octet_length(document::text) <= 8388608)
);
alter table public.lesson_boards enable row level security;

create function public.can_read_lesson_board(sid uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from sessions s left join lesson_boards b on b.session_id = s.id
    where s.id = sid and (
      public.is_class_teacher(s.class_id) or (
        public.is_enrolled(s.class_id) and
        -- Prefer the board's immutable audience after its first save.
        (case when b.session_id is null then s.group_id else b.group_id end is null
         or (case when b.session_id is null then s.group_id else b.group_id end) = public.my_group(s.class_id))
      )
    )
  );
$$;
create function public.can_write_lesson_board(sid uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from sessions s where s.id = sid and public.is_class_teacher(s.class_id));
$$;
create policy "lesson boards: audience reads" on public.lesson_boards for select to authenticated
  using (public.can_read_lesson_board(session_id));
create policy "lesson boards: teacher inserts" on public.lesson_boards for insert to authenticated
  with check (teacher_id = auth.uid() and exists (
    select 1 from public.sessions s where s.id = session_id and s.class_id = lesson_boards.class_id
      and s.teacher_id = auth.uid() and s.group_id is not distinct from lesson_boards.group_id
  ));
create policy "lesson boards: teacher updates" on public.lesson_boards for update to authenticated
  using (teacher_id = auth.uid() and public.is_class_teacher(class_id))
  with check (teacher_id = auth.uid() and public.is_class_teacher(class_id));

create function public.guard_lesson_board()
returns trigger language plpgsql set search_path = public as $$
begin
  if tg_op = 'UPDATE' then
    if new.session_id <> old.session_id or new.class_id <> old.class_id or new.teacher_id <> old.teacher_id
       or new.group_id is distinct from old.group_id then raise exception 'board audience is immutable'; end if;
    if new.revision < old.revision then return null; end if;
  end if;
  new.updated_at = now();
  return new;
end;
$$;
create trigger guard_lesson_board before insert or update on public.lesson_boards
  for each row execute function public.guard_lesson_board();

-- Derive ownership/audience on the server and retain the original audience on updates.
create function public.save_lesson_board(sid uuid, board_document jsonb)
returns uuid language sql security invoker set search_path = public as $$
  insert into public.lesson_boards(session_id, class_id, group_id, teacher_id, document, revision)
  select s.id, s.class_id, s.group_id, s.teacher_id, board_document, (board_document->>'revision')::bigint
  from public.sessions s where s.id = sid and s.teacher_id = auth.uid() and public.is_class_teacher(s.class_id)
  on conflict (session_id) do update set document = excluded.document, revision = excluded.revision
  returning session_id;
$$;

insert into storage.buckets(id, name, public, file_size_limit, allowed_mime_types)
values ('board-assets', 'board-assets', false, 20971520, array['image/png','image/jpeg','image/webp'])
on conflict (id) do nothing;
-- Paths are <session UUID>/<asset UUID>.png. The second segment is generated by the app.
create policy "board assets: teacher upload" on storage.objects for insert to authenticated
  with check (bucket_id = 'board-assets' and public.can_write_lesson_board(public.board_uuid((storage.foldername(name))[1])));
create policy "board assets: audience read" on storage.objects for select to authenticated
  using (bucket_id = 'board-assets' and public.can_read_lesson_board(public.board_uuid((storage.foldername(name))[1])));
create policy "board assets: teacher delete" on storage.objects for delete to authenticated
  using (bucket_id = 'board-assets' and public.can_write_lesson_board(public.board_uuid((storage.foldername(name))[1])));

-- A separate channel prevents students from impersonating board edits through class broadcasts.
create policy "board realtime: audience reads" on realtime.messages for select to authenticated
  using (realtime.topic() ~ '^board:[0-9a-fA-F-]{36}$'
         and public.can_read_lesson_board(public.board_uuid(split_part(realtime.topic(), ':', 2))));
create policy "board realtime: teacher sends" on realtime.messages for insert to authenticated
  with check (realtime.topic() ~ '^board:[0-9a-fA-F-]{36}$'
              and public.can_write_lesson_board(public.board_uuid(split_part(realtime.topic(), ':', 2))));

alter table public.materials add column group_id uuid;
-- The id intentionally has no ON DELETE SET NULL foreign key: group deletion must not widen access.
drop policy "materials: read teacher or enrolled" on public.materials;
create policy "materials: read teacher or group" on public.materials for select to authenticated
  using (public.is_class_teacher(class_id) or (public.is_enrolled(class_id) and (group_id is null or group_id = public.my_group(class_id))));
drop policy "materials: teacher insert" on public.materials;
create policy "materials: teacher insert" on public.materials for insert to authenticated
  with check (public.is_class_teacher(class_id) and uploaded_by = auth.uid() and public.group_in_class(group_id, class_id));
drop policy if exists "materials: teacher update" on public.materials;
create policy "materials: teacher update" on public.materials for update to authenticated
  using (public.is_class_teacher(class_id))
  with check (public.is_class_teacher(class_id) and public.group_in_class(group_id, class_id));
drop policy "materials bucket: read teacher or enrolled" on storage.objects;
create policy "materials bucket: read teacher or group" on storage.objects for select to authenticated
  using (bucket_id = 'materials' and (
    public.is_class_teacher((storage.foldername(name))[1]) or exists (
      select 1 from public.materials m where m.file_path = name
        and public.is_enrolled(m.class_id) and (m.group_id is null or m.group_id = public.my_group(m.class_id))
    )
  ));
